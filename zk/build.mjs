// Builds the Phase-4 circuit end to end:  npm run zk:build
//   1. compile zk/ring_balance.circom (circom 2, --O2)
//   2. Groth16 phase 2 on top of the PSE Perpetual Powers of Tau (ppot_0080, 2^16)
//   3. one fresh random contribution  (run more with `npm run zk:contribute` / a public ceremony before mainnet)
//   4. export: public/zk/ring_balance.{wasm,zkey}, api/_lib/zk-vk.ts
import { execSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { randomBytes } from 'node:crypto'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..')
const zk = path.join(root, 'zk')
const run = (cmd, cwd = root) => execSync(cmd, { cwd, stdio: 'inherit' })
const PTAU_URL = 'https://pse-trusted-setup-ppot.s3.eu-central-1.amazonaws.com/pot28_0080/ppot_0080_16.ptau'

mkdirSync(path.join(zk, '.deps', 'circomlib'), { recursive: true })
cpSync(path.join(root, 'node_modules', 'circomlib', 'circuits'), path.join(zk, '.deps', 'circomlib', 'circuits'), { recursive: true })
mkdirSync(path.join(zk, 'build'), { recursive: true })

// circom2 (WASI) only sees the current directory, so compile from inside zk/
run('npx circom2 ring_balance.circom --r1cs --wasm --O2 -l .deps -o build', zk)

const ptau = path.join(zk, '.deps', 'pot16.ptau')
if (!existsSync(ptau)) run(`curl -sSfL -o "${ptau}" ${PTAU_URL}`)

run('npx snarkjs groth16 setup zk/build/ring_balance.r1cs zk/.deps/pot16.ptau zk/build/rb_0000.zkey')
run(`npx snarkjs zkey contribute zk/build/rb_0000.zkey zk/build/rb_final.zkey --name="Parhelion phase-2 #1" -e="${randomBytes(64).toString('hex')}"`)
run('npx snarkjs zkey export verificationkey zk/build/rb_final.zkey zk/build/verification_key.json')

mkdirSync(path.join(root, 'public', 'zk'), { recursive: true })
copyFileSync(path.join(zk, 'build', 'ring_balance_js', 'ring_balance.wasm'), path.join(root, 'public', 'zk', 'ring_balance.wasm'))
copyFileSync(path.join(zk, 'build', 'rb_final.zkey'), path.join(root, 'public', 'zk', 'ring_balance.zkey'))
const vk = readFileSync(path.join(zk, 'build', 'verification_key.json'), 'utf8')
writeFileSync(
  path.join(root, 'api', '_lib', 'zk-vk.ts'),
  `/** Groth16 verification key for zk/ring_balance.circom. Generated by \`npm run zk:build\` — do not edit. */\n// prettier-ignore\nexport const VERIFICATION_KEY = ${vk.trim()} as const\n`,
)
console.log('\nZK artifacts written: public/zk/ring_balance.{wasm,zkey}, api/_lib/zk-vk.ts')
